package com.ghostlock.app.data.finish

import android.content.Context
import com.ghostlock.app.core.finish.FinishConfig
import com.ghostlock.app.core.finish.FinishScriptStore
import com.ghostlock.app.core.finish.FinishState
import com.ghostlock.app.core.finish.PayloadKind
import com.ghostlock.app.core.finish.PayloadSlot
import com.ghostlock.app.domain.finish.FinishEditorPort
import com.ghostlock.app.domain.finish.FinishEditorState
import com.ghostlock.app.domain.finish.FinishPayloadKind
import com.ghostlock.app.domain.finish.FinishPayloadSlot
import com.ghostlock.app.domain.finish.FinishRootManagerOption

/**
 * Maps the pure finish-editor contract onto the existing authoritative config and preview format.
 *
 * @param context Application context for persisted config, package facts, and preview storage.
 * @note Save changes only root manager, safe mode, and payload ordering/content; all other fields are copied.
 */
class FinishEditorAdapter(
    context: Context,
) : FinishEditorPort {
    private val applicationContext = context.applicationContext

    /** @return Current editor projection after loading persisted authoritative state. */
    override fun read(): FinishEditorState {
        FinishConfig.load(applicationContext)
        return FinishConfig.state.toDomainState()
    }

    /** Persists editor-owned fields while preserving settings and relay fields from current state. */
    override fun save(state: FinishEditorState) {
        FinishConfig.update(applicationContext, state.toCoreState(FinishConfig.state))
    }

    /** @return Absolute path generated by the unchanged existing preview renderer. */
    override fun preview(state: FinishEditorState): String =
        FinishScriptStore.preview(
            applicationContext,
            state.toCoreState(FinishConfig.state),
        ).absolutePath

    /** @return Pure editor projection including current manager installation facts. */
    private fun FinishState.toDomainState(): FinishEditorState = FinishEditorState(
        rootManager = rootManager,
        safeMode = safeMode,
        payloads = payloads.map { it.toDomainSlot() },
        rootManagers = FinishConfig.rootManagers.map { manager ->
            val installed = FinishConfig.installedPackages(applicationContext, manager).firstOrNull()
            FinishRootManagerOption(
                name = manager.name,
                installedPackage = installed,
                iconPackage = installed ?: manager.packages.firstOrNull().orEmpty(),
                launchOnly = manager.launchOnly,
            )
        },
    )

    /** @return Existing authoritative state with only editor-owned fields replaced. */
    private fun FinishEditorState.toCoreState(current: FinishState): FinishState = current.copy(
        rootManager = rootManager,
        safeMode = safeMode,
        payloads = payloads.map { it.toCoreSlot() },
    )

    /** @return Pure projection of one existing payload slot. */
    private fun PayloadSlot.toDomainSlot(): FinishPayloadSlot = FinishPayloadSlot(
        id = id,
        kind = kind.toDomainKind(),
        enabled = enabled,
        scriptMode = scriptMode,
        command = command,
        scriptUri = scriptUri,
        lkmUri = lkmUri,
        lkmParams = lkmParams,
    )

    /** @return Existing payload slot preserving every editor field. */
    private fun FinishPayloadSlot.toCoreSlot(): PayloadSlot = PayloadSlot(
        id = id,
        kind = kind.toCoreKind(),
        enabled = enabled,
        scriptMode = scriptMode,
        command = command,
        scriptUri = scriptUri,
        lkmUri = lkmUri,
        lkmParams = lkmParams,
    )

    /** @return Pure payload kind equivalent. */
    private fun PayloadKind.toDomainKind(): FinishPayloadKind = when (this) {
        PayloadKind.Root -> FinishPayloadKind.Root
        PayloadKind.Command -> FinishPayloadKind.Command
        PayloadKind.Lkm -> FinishPayloadKind.Lkm
    }

    /** @return Existing authoritative payload kind equivalent. */
    private fun FinishPayloadKind.toCoreKind(): PayloadKind = when (this) {
        FinishPayloadKind.Root -> PayloadKind.Root
        FinishPayloadKind.Command -> PayloadKind.Command
        FinishPayloadKind.Lkm -> PayloadKind.Lkm
    }
}
