/**
 * Immutable Material/Miuix pair for one project icon meaning and visual variant.
 *
 * @property material Material icon selected by existing Material call sites.
 * @property miuix Miuix icon or the Miuix help fallback when that side has no counterpart.
 * @property materialFallback True only when the Material side uses the project help fallback.
 * @property miuixFallback True only when the Miuix side uses the project help fallback.
 * @note P-UI-ICON-001 keeps lookup compile-time and never performs reflective icon discovery.
 */
@Immutable
class IconPair internal constructor(
    val material: ImageVector,
    val miuix: ImageVector,
    val materialFallback: Boolean = false,
    val miuixFallback: Boolean = false,
) {
    /**
     * Resolves the icon for one active renderer.
     *
     * @param uiMode Active Material or Miuix renderer.
     * @return The matching icon, including the recorded per-side fallback when necessary.
     */
    fun resolve(uiMode: UiMode): ImageVector = when (uiMode) {
        UiMode.Material -> material
        UiMode.Miuix -> miuix
    }
}

