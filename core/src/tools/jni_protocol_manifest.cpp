/** @file tools/jni_protocol_manifest.cpp
 *  Export the boundary's tables as TSV: ops, keys, statuses, and the frame constants.
 *
 *  Why it exists: the Kotlin side must not hand-copy the op/key/status lists (AGENTS: a cross-end
 *  list is exported by the side that owns it, never transcribed). The Kotlin test reads this
 *  export and compares it against its own tables, so a rename on either side fails a test instead
 *  of a device run.
 *
 *  Output is stable and diffable: a header comment, then one row per entry, sorted by number.
 */
#include <cstdio>

#include "backend/cve_2026_43284/embed/libcxx_blob.hpp"
#include "backend/cve_2026_43284/embed/splicehelper_blob.hpp"
#include "backend/cve_2026_43284/hook/sentry_hook.hpp"
#include "boundary/protocol/ops_43284.hpp"
#include "boundary/protocol/session_protocol.hpp"
#include "support/sha256.hpp"

int main() {
    using ghostlock::jni::frame_key_name;
    using ghostlock::jni::frame_op_name;
    using ghostlock::jni::frame_status_name;
    std::printf("# ghostlock jni protocol manifest (generated by jni_protocol_manifest)\n");
    std::printf("frame.magic\t0x%08x\n", ghostlock::jni::kFrameMagic);
    std::printf("frame.version\t%u\n", static_cast<unsigned>(ghostlock::jni::kFrameVersion));
    std::printf("frame.header_size\t%zu\n", ghostlock::jni::kFrameHeaderSize);
    std::printf("frame.max_entries\t%zu\n", ghostlock::jni::kFrameMaxEntries);
    std::printf("frame.max_bytes\t%zu\n", ghostlock::jni::kFrameMaxBytes);
    for (std::uint16_t i = 0U; i < static_cast<std::uint16_t>(ghostlock::jni::FrameOp::Count); ++i) {
        std::printf("op\t%s\t%u\n", frame_op_name(ghostlock::jni::frame_op_of(i)),
                    static_cast<unsigned>(i));
    }
    const std::uint16_t keys[] = {1U, 2U, 3U, 4U, 5U, 6U, 7U, 8U, 9U, 10U, 11U, 12U, 13U, 14U, 15U,
                                  16U, 17U, 18U, 19U, 20U, 32U, 33U, 34U, 35U, 36U,
                                  40U, 41U, 42U, 43U, 44U, 45U, 46U, 47U, 48U,
                                  50U, 51U, 52U, 53U, 54U};
    for (const std::uint16_t raw : keys) {
        std::printf("key\t%s\t%u\n", frame_key_name(ghostlock::jni::frame_key_of(raw)),
                    static_cast<unsigned>(raw));
    }
    for (std::int32_t i = 0; i >= -17; --i) {
        std::printf("status\t%s\t%d\n", frame_status_name(static_cast<ghostlock::jni::FrameStatus>(i)), i);
    }
    /* 边界那两张图：设备侧会按同样的字节算摘要，两端必须一致，所以摘要也由 native 导出，
     * 而不是在 Kotlin 里手抄。 */
    {
        using namespace ghostlock::backend::cve_2026_43284;
        char hex[65] = {};
        const auto *helper = embed::splicehelper_bytes();
        const std::size_t helper_size = embed::splicehelper_padded_size();
        ghostlock::support::sha256_hex(ghostlock::support::sha256(helper, helper_size), hex);
        std::printf("image\tsplice_helper\t%s\n", hex);
        std::printf("image_size\tsplice_helper\t%zu\n", helper_size);
        const hook::SentryPlan plan = hook::device_sentry_plan();
        std::uint8_t payload[1024] = {};
        std::size_t payload_size = 0U;
        /* 钩子计划的四个数也导出：设备门禁按它们校验真机上回来的值，Kotlin/脚本都不手抄。 */
        std::uint32_t branch = 0U;
        if (hook::hook_branch(plan, branch) == hook::SentryError::Ok) {
            std::printf("hook\tbranch_word\t0x%08x\n", static_cast<unsigned>(branch));
        }
        std::printf("hook\tdisplaced_word\t0x%08x\n",
                    static_cast<unsigned>(plan.displaced_instruction));
        std::printf("hook\tsite_offset\t%llu\n",
                    static_cast<unsigned long long>(plan.hook_file_offset));
        std::printf("hook\tlanding_offset\t%llu\n",
                    static_cast<unsigned long long>(plan.payload_file_offset));
        if (hook::build_sentry_payload(plan, payload, sizeof(payload), payload_size) ==
            hook::SentryError::Ok) {
            ghostlock::support::sha256_hex(ghostlock::support::sha256(payload, payload_size), hex);
            std::printf("image\tlanding_payload\t%s\n", hex);
            std::printf("image_size\tlanding_payload\t%zu\n", payload_size);
        }
    }
    return 0;
}
