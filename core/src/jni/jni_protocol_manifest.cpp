/** @file jni/jni_protocol_manifest.cpp
 *  Export the boundary's tables as TSV: ops, keys, statuses, and the frame constants.
 *
 *  Why it exists: the Kotlin side must not hand-copy the op/key/status lists (AGENTS: a cross-end
 *  list is exported by the side that owns it, never transcribed). The Kotlin test reads this
 *  export and compares it against its own tables, so a rename on either side fails a test instead
 *  of a device run.
 *
 *  Output is stable and diffable: a header comment, then one row per entry, sorted by number.
 */
#include <cstdio>

#include "jni/session_protocol.hpp"

int main() {
    using ghostlock::jni::frame_key_name;
    using ghostlock::jni::frame_op_name;
    using ghostlock::jni::frame_status_name;
    std::printf("# ghostlock jni protocol manifest (generated by jni_protocol_manifest)\n");
    std::printf("frame.magic\t0x%08x\n", ghostlock::jni::kFrameMagic);
    std::printf("frame.version\t%u\n", static_cast<unsigned>(ghostlock::jni::kFrameVersion));
    std::printf("frame.header_size\t%zu\n", ghostlock::jni::kFrameHeaderSize);
    std::printf("frame.max_entries\t%zu\n", ghostlock::jni::kFrameMaxEntries);
    std::printf("frame.max_bytes\t%zu\n", ghostlock::jni::kFrameMaxBytes);
    for (std::uint16_t i = 0U; i < static_cast<std::uint16_t>(ghostlock::jni::FrameOp::Count); ++i) {
        std::printf("op\t%s\t%u\n", frame_op_name(ghostlock::jni::frame_op_of(i)),
                    static_cast<unsigned>(i));
    }
    const std::uint16_t keys[] = {1U, 2U, 3U, 4U, 5U, 6U, 7U, 8U, 9U, 10U, 11U, 12U, 13U, 14U, 15U,
                                  16U, 17U, 18U, 19U, 20U, 32U, 33U, 34U, 35U, 36U,
                                  40U, 41U, 42U, 43U, 44U, 45U, 46U, 47U, 48U,
                                  50U, 51U, 52U, 53U, 54U};
    for (const std::uint16_t raw : keys) {
        std::printf("key\t%s\t%u\n", frame_key_name(ghostlock::jni::frame_key_of(raw)),
                    static_cast<unsigned>(raw));
    }
    for (std::int32_t i = 0; i >= -17; --i) {
        std::printf("status\t%s\t%d\n", frame_status_name(static_cast<ghostlock::jni::FrameStatus>(i)), i);
    }
    return 0;
}
