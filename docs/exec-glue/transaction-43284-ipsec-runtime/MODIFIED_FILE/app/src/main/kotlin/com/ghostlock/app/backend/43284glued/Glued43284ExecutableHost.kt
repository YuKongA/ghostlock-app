package com.ghostlock.app.backend.cve43284glued

import android.content.Context
import com.ghostlock.app.backend.cve43284glued.AndroidIpSecRuntime
import com.ghostlock.app.backend.core.ExecutableShizukuHost
import com.ghostlock.app.shizuku.host.ShizukuBackendHosts

/**
 * Shizuku peer adapter for the fixed 43284 Glued executable and its host-domain IPsec lifetime.
 *
 * @param userServiceContext Context owned by this UserService process, used to acquire IPsec state.
 * @note Caller argv must be empty; only this adapter constructs the upstream runtime flags.
 */
internal class Glued43284ExecutableHost(private val userServiceContext: Context) : ExecutableShizukuHost(
    context = userServiceContext,
    backendId = ShizukuBackendHosts.CVE_43284_GLUED,
    binaryName = "lib43284Glued.so",
    allowedFiles = setOf("finish.sh", "payload"),
) {
    private var ipSecRuntime: AndroidIpSecRuntime? = null

    /**
     * Creates this UserService process's IPsec runtime and returns upstream parser arguments.
     *
     * @param arguments the already validated AIDL argv; 43284 accepts no caller-supplied flags.
     * @return only values generated by this host's live runtime, never received over Binder.
     * @throws IllegalArgumentException when the AIDL caller supplies any arbitrary argument.
     * @throws IllegalStateException when this UserService cannot acquire its IPsec resources.
     * @note The runtime remains owned here until the child exits or this host is destroyed.
     */
    @Synchronized
    override fun prepareExecutableArguments(arguments: List<String>): List<String> {
        require(arguments.isEmpty()) { "43284 runtime arguments are host-generated" }
        val runtime = AndroidIpSecRuntime.create(userServiceContext)
        ipSecRuntime = runtime
        return runtime.arguments
    }

    /**
     * Releases this adapter's transform, SPI, and UDP encapsulation socket after child teardown.
     *
     * @throws IllegalStateException when any owned IPsec resource fails to close.
     * @note The field is cleared before close so a repeated destroy remains idempotent.
     */
    @Synchronized
    override fun finishExecutableRun() {
        val runtime = ipSecRuntime
        ipSecRuntime = null
        runtime?.close()
    }
}
